/** Adds the widget's `<receiver>` to the manifest's application, once. */
function addReceiver(manifest, packageName) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  const name = `${packageName}.widget.${PROVIDER}`;
  application.receiver = (application.receiver ?? []).filter((r) => r.$['android:name'] !== name);
  application.receiver.push({
    $: {
      'android:name': name,
      'android:exported': 'false',
      'android:label': '@string/capture_widget_label',
    },
    'intent-filter': [
      { action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } }] },
    ],
    'meta-data': [
      {
        $: {
          'android:name': 'android.appwidget.provider',
          'android:resource': '@xml/capture_widget_info',
        },
      },
    ],
  });
  return manifest;
}

const REFRESH = 'widget.CaptureWidgetProvider.refresh(this)';

/** Makes MainApplication.onCreate refresh the widget, once. */
function addRefresh(contents, packageName) {
  if (contents.includes(REFRESH)) return contents;
  const anchor = 'super.onCreate()';
  if (!contents.includes(anchor))
    throw new Error(`capture-widget: no "${anchor}" in MainApplication`);
  return contents.replace(anchor, `${anchor}\n    ${packageName}.${REFRESH}`);
}

const KEEP_INTENT_MARKER = '// capture-widget: keep the newest intent';
const KEEP_INTENT = `  ${KEEP_INTENT_MARKER}
  // When Android restores this activity after its process was killed, the widget's link arrives
  // here before JavaScript runs, and React Native drops it. Keeping it as the activity's intent
  // lets Linking.getInitialURL() find it.
  override fun onNewIntent(intent: Intent) {
    setIntent(intent)
    super.onNewIntent(intent)
  }

`;

/** Makes MainActivity keep the newest intent, once. */
function addKeepIntent(contents) {
  if (contents.includes(KEEP_INTENT_MARKER)) return contents;
  const anchor = '  override fun getMainComponentName()';
  if (!contents.includes(anchor))
    throw new Error(`capture-widget: no "${anchor.trim()}" in MainActivity`);
  const withImport = contents.includes('import android.content.Intent\n')
    ? contents
    : contents.replace(/^(package [^\n]+\n)/, '$1\nimport android.content.Intent\n');
  return withImport.replace(anchor, KEEP_INTENT + anchor);
}

function settings(config) {
  const packageName = config.android?.package;
  const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
  if (!packageName || !scheme) throw new Error('capture-widget: needs android.package and scheme');
  return { packageName, scheme };
}

module.exports = (config) => {
  const { packageName, scheme } = settings(config);
  config = withAndroidManifest(config, (mod) => {
    addReceiver(mod.modResults, packageName);
    return mod;
  });
  config = withMainApplication(config, (mod) => {
    if (mod.modResults.language !== 'kt')
      throw new Error('capture-widget: MainApplication is not Kotlin');
    mod.modResults.contents = addRefresh(mod.modResults.contents, packageName);
    return mod;
  });
  config = withMainActivity(config, (mod) => {
    if (mod.modResults.language !== 'kt')
      throw new Error('capture-widget: MainActivity is not Kotlin');
    mod.modResults.contents = addKeepIntent(mod.modResults.contents);
    return mod;
  });
  return withDangerousMod(config, [
    'android',
    (mod) => {
      const main = path.join(mod.modRequest.platformProjectRoot, 'app/src/main');
      for (const [file, contents] of Object.entries(widgetFiles({ packageName, scheme }))) {
        fs.mkdirSync(path.dirname(path.join(main, file)), { recursive: true });
        fs.writeFileSync(path.join(main, file), contents);
      }
      return mod;
    },
  ]);
};
module.exports.widgetFiles = widgetFiles;
module.exports.addReceiver = addReceiver;
module.exports.addRefresh = addRefresh;
module.exports.addKeepIntent = addKeepIntent;
