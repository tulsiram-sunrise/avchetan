// The home-screen quick-capture bar (docs/product/android-widget.md): a native AppWidgetProvider
// whose only job is to open `<scheme>://capture?from=widget`. No JavaScript runs for the widget.
// android/ is generated, so every file is written here on each prebuild.

const PROVIDER = 'CaptureWidgetProvider';

const xml = (body) => `<?xml version="1.0" encoding="utf-8"?>\n${body.trim()}\n`;

function colors({ background, hint, accent }) {
  return `
    <color name="capture_widget_background">${background}</color>
    <color name="capture_widget_hint">${hint}</color>
    <color name="capture_widget_accent">${accent}</color>`;
}

