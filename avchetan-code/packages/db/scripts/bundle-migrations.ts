/**
 * Bundles drizzle-kit's generated SQL migrations into TypeScript modules so every
 * runtime (Tauri webview, React Native, Node server, tests) can apply them without
 * file-system access. Run via `pnpm db:generate` (after drizzle-kit generate).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type JournalEntry = { idx: number; tag: string };

const DIALECTS = [
  { dir: 'sqlite', exportName: 'sqliteMigrations' },
  { dir: 'pg', exportName: 'pgMigrations' },
] as const;

const root = join(import.meta.dirname, '..');

for (const { dir, exportName } of DIALECTS) {
  const migrationsDir = join(root, 'migrations', dir);
  const journal = JSON.parse(
    readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'),
  ) as {
    entries: JournalEntry[];
  };
  const migrations = journal.entries
    .sort((a, b) => a.idx - b.idx)
    .map(({ tag }) => ({
      tag,
      statements: readFileSync(join(migrationsDir, `${tag}.sql`), 'utf8')
        .split('--> statement-breakpoint')
        .map((statement) => statement.trim())
        .filter((statement) => statement.length > 0),
    }));

  const source = [
    `// GENERATED by scripts/bundle-migrations.ts from migrations/${dir}. Do not edit.`,
    `import type { Migration } from './runner';`,
    '',
    `export const ${exportName}: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};`,
    '',
  ].join('\n');

  writeFileSync(join(root, 'src', 'migrations', `${dir}.generated.ts`), source);
  process.stdout.write(`bundled ${migrations.length} ${dir} migration(s)\n`);
}
